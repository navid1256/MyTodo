// Push-only worker. Offline caching and installability are a separate roadmap step.
self.addEventListener('install', (event) => event.waitUntil(self.skipWaiting()));

self.addEventListener('push', (event) => {
    let payload = {};
    try {
        payload = event.data?.json() || {};
    } catch {
        // Even malformed/empty pushes must produce a user-visible notification.
        payload = {};
    }
    const title = typeof payload.title === 'string' ? payload.title.slice(0, 512) : 'MyTodo';
    const body = typeof payload.body === 'string' ? payload.body.slice(0, 1000) : 'You have a task reminder.';
    const tag = typeof payload.tag === 'string' ? payload.tag : 'mytodo-reminder';
    let url = new URL('/notifications', self.location.origin);
    try {
        const requested = new URL(payload.url, self.location.origin);
        if (requested.origin === self.location.origin && ['/notifications', '/manage-tasks', '/'].includes(requested.pathname)) {
            url = requested;
        }
    } catch {
        // Never open an external origin from a push payload.
    }
    event.waitUntil(self.registration.showNotification(title, {
        body, tag, data: { url: url.href },
        icon: '/assets/img/user-default-avatar.webp'
    }));
});

/** Temporarily stores only the latest test click's stages, excluding payloads and raw errors. */
async function saveTestClickDiagnostics(diagnostics) {
    try {
        const cache = await self.caches.open('mytodo-push-click-debug-v1');
        await cache.put(new URL('/__mytodo_push_click_debug__', self.location.origin).href,
            new Response(JSON.stringify(diagnostics), { headers: { 'Content-Type': 'application/json' } }));
    } catch {
        // Diagnostic storage must not change the notification's navigation outcome.
    }
}

// Temporary instrumentation is restricted to explicitly tagged test notifications.
self.addEventListener('notificationclick', (event) => {
    const traceId = /^mytodo-push-test-([0-9a-f]{16})$/.exec(event.notification.tag || '')?.[1];
    const diagnostics = traceId ? {
        event: 'push_test_click', entryPoint: 'notificationclick', traceId,
        stages: ['click-received'], errorName: null
    } : null;
    let url = new URL('/notifications', self.location.origin);
    try {
        const requested = new URL(event.notification.data?.url, self.location.origin);
        if (requested.origin === self.location.origin && ['/notifications', '/manage-tasks', '/'].includes(requested.pathname)) url = requested;
    } catch {
        // A notification may have been generated by an older worker version.
    }
    event.waitUntil((async () => {
        try {
            event.notification.close();
            diagnostics?.stages.push('matching-windows');
            const windows = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
            const existing = windows.find((client) => new URL(client.url).origin === self.location.origin);
            if (existing) {
                diagnostics?.stages.push('window-found', 'navigating');
                await existing.navigate(url.href);
                diagnostics?.stages.push('navigation-complete', 'focusing');
                await existing.focus();
                diagnostics?.stages.push('focus-complete');
            } else {
                diagnostics?.stages.push('opening-window');
                await self.clients.openWindow(url.href);
                diagnostics?.stages.push('window-opened');
            }
        } catch (error) {
            if (diagnostics) {
                const allowedNames = ['Error', 'TypeError', 'InvalidAccessError', 'SecurityError',
                    'AbortError', 'InvalidStateError', 'NotAllowedError', 'NotSupportedError', 'NetworkError'];
                diagnostics.errorName = allowedNames.includes(error?.name) ? error.name : 'Error';
            }
            throw error;
        } finally {
            if (diagnostics) await saveTestClickDiagnostics(diagnostics);
        }
    })());
});
