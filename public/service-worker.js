// Push-only worker. Offline caching and installability are a separate roadmap step.
self.addEventListener('install', (event) => event.waitUntil(self.skipWaiting()));

self.addEventListener('push', (event) => {
    let payload = {};
    try {
        payload = event.data?.json() || {};
    } catch {
        // Even malformed/empty pushes must produce a user-visible notification.
        payload = {};
    }
    const title = typeof payload.title === 'string' ? payload.title.slice(0, 512) : 'MyTodo';
    const body = typeof payload.body === 'string' ? payload.body.slice(0, 1000) : 'You have a task reminder.';
    const tag = typeof payload.tag === 'string' ? payload.tag : 'mytodo-reminder';
    let url = new URL('/notifications', self.location.origin);
    try {
        const requested = new URL(payload.url, self.location.origin);
        if (requested.origin === self.location.origin && ['/notifications', '/manage-tasks', '/'].includes(requested.pathname)) {
            url = requested;
        }
    } catch {
        // Never open an external origin from a push payload.
    }
    event.waitUntil(self.registration.showNotification(title, {
        body, tag, data: { url: url.href },
        icon: '/assets/img/user-default-avatar.webp'
    }));
});

self.addEventListener('notificationclick', (event) => {
    event.notification.close();
    let url = new URL('/notifications', self.location.origin);
    try {
        const requested = new URL(event.notification.data?.url, self.location.origin);
        if (requested.origin === self.location.origin && ['/notifications', '/manage-tasks', '/'].includes(requested.pathname)) url = requested;
    } catch {
        // A notification may have been generated by an older worker version.
    }
    event.waitUntil((async () => {
        const windows = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
        const existing = windows.find((client) => new URL(client.url).origin === self.location.origin);
        if (existing) {
            await existing.navigate(url.href);
            await existing.focus();
        } else {
            await self.clients.openWindow(url.href);
        }
    })());
});
